"""Real Web -> API -> Neo4j acceptance. No intercepted or mocked requests."""
import json
import re
from pathlib import Path
from playwright.sync_api import sync_playwright,expect

def main():
    folder=Path('portable/evidence-ci/screenshots')
    folder.mkdir(parents=True,exist_ok=True)
    errors=[]
    shots=[]
    with sync_playwright() as p:
        browser=p.chromium.launch(headless=True)
        page=browser.new_page(viewport={'width':1440,'height':1050})
        page.on('pageerror',lambda error:errors.append(str(error)))
        page.goto('http://localhost:3000')
        page.wait_for_load_state('networkidle')
        def capture(file,title):
            page.evaluate('window.scrollTo(0,0)')
            page.screenshot(path=str(folder/file),full_page=True)
            shots.append({'file':file,'title':title})
        def switch(label):
            page.get_by_role('navigation',name='Phân hệ phân tích').get_by_role('button',name=label,exact=True).click()
            expect(page.get_by_role('status')).to_have_count(0)
            page.wait_for_load_state('networkidle')
            expect(page.locator('.u-panel')).to_be_visible()
        expect(page.locator('.a-overview-grid .a-card')).to_have_count(4)
        expect(page.locator('.a-stats article')).to_have_count(6)
        expect(page.locator('.a-stats')).to_contain_text('380')
        expect(page.locator('.a-outcomes strong')).to_have_text(['40,8%','24,5%','34,7%'])
        expect(page.locator('.a-outcomes small')).to_have_text(['155 trận','93 trận','132 trận'])
        assert not page.locator('.a-chart svg').first.evaluate('(svg)=>svg.innerHTML.includes("NaN")')
        capture('00-tong-quan.png','Trang chủ · Tổng quan Premier League')
        switch('Bảng xếp hạng')
        expect(page.locator('.a-card').first.locator('tbody tr')).to_have_count(20)
        expect(page.locator('.a-card').first).to_contain_text('Liverpool')
        capture('12-bang-xep-hang.png','Bảng xếp hạng thực tế và KNN')
        page.get_by_role('button',name='Ước tính theo KNN',exact=True).click()
        expect(page.locator('.a-card').first.locator('tbody tr')).to_have_count(20)
        expect(page.locator('.a-card').first).to_contain_text('Hạng KNN')
        switch('Đội bóng')
        expect(page.locator('.a-form span')).to_have_count(10)
        expect(page.locator('.a-form')).to_contain_text('T')
        expect(page.locator('.a-form')).to_contain_text('B')
        capture('13-doi-bong.png','Phân tích đội bóng')
        page.locator('.u-controls label').filter(has_text='Chọn đội bóng').locator('select').select_option('MCI')
        expect(page.locator('.a-card').first).to_contain_text('Manchester City')
        switch('So sánh đội bóng')
        expect(page.locator('.a-bars-paired .a-bar-row')).to_have_count(8)
        capture('14-so-sanh-doi-bong.png','So sánh Liverpool và Arsenal')
        switch('Tiềm năng cầu thủ')
        expect(page.locator('.u-panel tbody tr')).to_have_count(25)
        expect(page.locator('.u-meta')).to_contain_text('bundle_')
        capture('01-tiem-nang.png','Tiềm năng và duy trì cầu thủ')
        page.locator('.u-heading select').select_option('2022-2023')
        page.locator('.u-panel>label').filter(has_text='Cửa sổ phân tích').locator('select').select_option('1')
        page.wait_for_load_state('networkidle')
        expect(page.locator('.u-pages').first).to_contain_text('554 dòng')
        page.locator('.u-heading select').select_option('2024-2025')
        page.wait_for_load_state('networkidle')
        switch('Phong độ CLB')
        expect(page.locator('.u-phases')).to_have_count(2)
        capture('02-phong-do-clb.png','Phong độ CLB qua bốn giai đoạn')
        page.locator('.u-controls label').filter(has_text='Đối chiếu').locator('select').select_option('MCI')
        expect(page.locator('.u-panel')).to_contain_text('Manchester City')
        switch('Radar cầu thủ')
        page.locator('.u-controls label').filter(has_text='Cầu thủ 1').locator('select').select_option('Erling Haaland_2024-2025')
        page.locator('.u-controls label').filter(has_text='Cầu thủ 2').locator('select').select_option('Alexander Isak_2024-2025')
        page.get_by_role('button',name='Tìm và lưu cầu thủ tương đồng').click()
        expect(page.locator('.f-saved')).to_contain_text('player_similarity_',timeout=30000)
        capture('03-radar-cau-thu.png','Radar và tương đồng đã lưu Neo4j')
        switch('Mô phỏng')
        page.get_by_role('button',name='Tính và lưu định giá').click()
        expect(page.locator('.u-value>strong')).to_have_text('€70,9M',timeout=30000)
        run=re.search(r'valuation_[a-f0-9]+',page.locator('.u-value .f-saved').inner_text()).group()
        capture('04-dinh-gia.png','Định giá và quỹ đạo đã lưu Neo4j')
        switch('Chuyển nhượng')
        expect(page.locator('.u-panel .u-table').first.locator('tbody tr')).to_have_count(20)
        capture('07-chuyen-nhuong.png','Thu–chi chuyển nhượng và hiệu quả chi tiêu')
        switch('Thị trường & CLB')
        expect(page.locator('.u-season-stats')).to_be_visible()
        capture('11-thi-truong-clb.png','Thị trường, bàn thắng theo 15 phút và CLB')
        switch('RFM & GMM')
        expect(page.locator('.u-panel tbody tr')).to_have_count(28)
        capture('08-rfm-gmm.png','Phân cụm GMM thật')
        page.locator('.u-panel>label').filter(has_text='Phương pháp').locator('select').select_option('rules')
        expect(page.locator('.u-panel tbody tr')).to_have_count(24)
        switch('Báo cáo & dữ liệu')
        page.locator('.u-controls label').filter(has_text='Lần chạy').locator('select').select_option(run)
        page.get_by_role('button',name='Xem bản lưu').click()
        expect(page.locator('pre')).to_contain_text('70.9',timeout=30000)
        capture('09-danh-muc.png','Lịch sử phân tích và danh mục Database')
        page.get_by_role('navigation',name='Phân hệ phân tích').get_by_role('button',name='Trận & KNN',exact=True).click()
        expect(page.locator('.f-evaluation')).to_be_visible()
        page.get_by_role('button',name='Ước tính kết quả →').click()
        expect(page.locator('.f-model-id')).to_contain_text('wdl2_',timeout=30000)
        expect(page.locator('.v2-neighbors tbody tr')).to_have_count(15)
        capture('05-du-doan-tran.png','Dự đoán trước trận · đối đầu và cosine')
        page.get_by_role('button',name='Mở kết quả đã lưu').click()
        expect(page.locator('.f-result')).to_contain_text('Đã đọc lại đúng phiên bản')
        page.get_by_role('button',name='Trong trận',exact=True).click()
        page.get_by_label('Phút thi đấu',exact=True).fill('60')
        page.get_by_label('Bàn chủ nhà',exact=True).fill('1')
        page.get_by_label('Chủ nhà Kiểm soát bóng',exact=True).fill('65')
        page.get_by_label('Đội khách Kiểm soát bóng',exact=True).fill('35')
        page.get_by_label('Chủ nhà Tổng số cú sút',exact=True).fill('14')
        page.get_by_label('Đội khách Tổng số cú sút',exact=True).fill('4')
        page.get_by_label('Chủ nhà Sút trúng đích',exact=True).fill('6')
        page.get_by_label('Đội khách Sút trúng đích',exact=True).fill('0')
        page.get_by_role('button',name='Ước tính kết quả →').click()
        expect(page.locator('.v2-note')).to_contain_text('chưa được kiểm chứng',timeout=30000)
        capture('15-trong-tran.png','Trong trận · tỉ số, phút và thống kê tương đồng')
        page.get_by_label('Đã kết thúc',exact=True).check()
        page.get_by_role('button',name='Ước tính kết quả →').click()
        expect(page.locator('.f-prob-values .home_win strong')).to_have_text('100.0%',timeout=30000)
        page.set_viewport_size({'width':390,'height':844})
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
        capture('16-du-doan-mobile.png','Dự đoán trong trận trên điện thoại')
        page.set_viewport_size({'width':1440,'height':1050})
        page.get_by_role('button',name='Đội tương đồng · KNN').click()
        expect(page.locator('.f-knn tbody tr')).to_have_count(5)
        capture('06-knn.png','KNN đội tương đồng')
        switch('Phong độ CLB')
        page.set_viewport_size({'width':390,'height':844})
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
        capture('10-mobile.png','Giao diện điện thoại')
        page.get_by_role('button',name='Mở điều hướng').click()
        page.get_by_role('navigation',name='Phân hệ phân tích').get_by_role('button',name='Trang chủ',exact=True).click()
        expect(page.locator('.a-overview-grid .a-card')).to_have_count(4)
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
        browser.close()
    assert not errors,errors
    (folder/'checks.json').write_text(json.dumps({'status':'passed','mode':'real Web/API/Neo4j; local reports removed','javascript_errors':errors,'screenshots':shots},ensure_ascii=False,indent=2),encoding='utf-8')
    print('Real browser acceptance passed;',len(shots),'screenshots')

if __name__=='__main__':
    main()
